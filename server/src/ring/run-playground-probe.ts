import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { RingPlaygroundClient, RingPlaygroundError, type PlaygroundClientOptions } from './playground-client.js';
import { extractPlaygroundDevices } from './playground-devices.js';
import { redactProbeReport, summarizePlaygroundResponse } from './playground-probe-report.js';

const MAX_HISTORY_PAGES = 5;

export interface PlaygroundProbeOptions {
  accessToken: string;
  apiBaseUrl: string;
  historyDeviceId?: string | null;
  printDeviceIds?: boolean;
  outputDirectory: string;
  clientOptions?: PlaygroundClientOptions;
  now?: () => Date;
  writeOutput?: (line: string) => void;
}

export interface PlaygroundProbeResult {
  reportPath: string;
  report: Record<string, unknown>;
}

function safeErrorCode(error: unknown): string {
  if (error instanceof RingPlaygroundError) return error.code;
  return 'probe_failed';
}

function validDeviceId(value: string): boolean {
  return value.length > 0 && value.length <= 512 && value !== '.' && value !== '..'
    && ![...value].some((character) => character.charCodeAt(0) < 32 || character.charCodeAt(0) === 127);
}

function localDate(now: Date): string {
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

function writeArtifacts(report: Record<string, unknown>, outputDirectory: string, now: Date, cwd: string): string {
  mkdirSync(outputDirectory, { recursive: true });
  const stamp = now.toISOString().replace(/[:.]/g, '-');
  const filename = `probe-${localDate(now)}-${stamp}.json`;
  const reportPath = join(outputDirectory, filename);
  const safeReport = redactProbeReport(report);
  writeFileSync(reportPath, `${JSON.stringify(safeReport, null, 2)}\n`, { flag: 'wx', mode: 0o600 });

  const readmePath = join(outputDirectory, 'README.md');
  if (!existsSync(readmePath)) {
    writeFileSync(readmePath, [
      '# Ring Developer Playground probe reports',
      '',
      'Reports in this folder are generated by `npm run ring:probe` after a human runs it against the official Ring Developer Playground.',
      'A devices-only run is possible without a device ID. Reports contain response structure, allow-listed event-type strings, subtype/classification field paths and JSON types, and timestamp-format classifications only; they are not replayable API fixtures and do not contain raw response values, tokens, device IDs, email addresses, or URLs.',
      'Do not hand-author a report or treat a mocked test response as Ring evidence. Review each real report for privacy before sharing or committing it.',
      '',
    ].join('\n'), { flag: 'wx', mode: 0o600 });
  }
  return relative(cwd, reportPath);
}

export async function runPlaygroundProbe(options: PlaygroundProbeOptions): Promise<PlaygroundProbeResult> {
  const now = options.now?.() ?? new Date();
  const output = options.writeOutput ?? ((line: string) => console.log(line));
  const historyDeviceId = options.historyDeviceId?.trim() || null;
  if (historyDeviceId && !validDeviceId(historyDeviceId)) {
    throw new Error('RING_HISTORY_DEVICE_ID must be a safe, short, single-line value. The value was not printed.');
  }

  const client = new RingPlaygroundClient(options.apiBaseUrl, options.accessToken, options.clientOptions);
  const report: Record<string, unknown> = {
    reportKind: 'structure-only-playground-probe',
    sourceLabel: 'ring_playground (operator-configured; not independently inferred)',
    captureDate: localDate(now),
    capturedAt: now.toISOString(),
    credentialHandling: 'Server-side authorization credential read from local process environment; it is not included in this report.',
    calls: [],
    historyDeviceSelection: historyDeviceId
      ? { configuredInServerEnvironment: true, identifierValue: '<redacted>', identifierFormat: 'operator-supplied; not inferred' }
      : { configuredInServerEnvironment: false, identifierValue: '<not configured>', identifierFormat: 'not provided; no ID inferred' },
    historyPagination: { pageCount: 0, truncated: false },
  };
  const calls = report.calls as Array<Record<string, unknown>>;
  let devices: ReturnType<typeof extractPlaygroundDevices> = { devices: [], shapeUnrecognized: true };

  try {
    const devicePayload = await client.getDevices();
    devices = extractPlaygroundDevices(devicePayload);
    calls.push({ operation: 'list_devices', response: summarizePlaygroundResponse(devicePayload, 'devices') });

    if (historyDeviceId) {
      const history = await client.getEventHistoryPages(historyDeviceId, MAX_HISTORY_PAGES);
      report.historyPagination = {
        pageCount: history.pages.length,
        truncated: history.truncated,
        ...(history.paginationIssue ? { paginationIssue: history.paginationIssue } : {}),
      };
      calls.push(...history.pages.map((page, index) => ({
        operation: 'event_history',
        pageNumber: index + 1,
        response: summarizePlaygroundResponse(page, 'event_history'),
      })));
    }
  } catch (error) {
    report.failure = {
      code: safeErrorCode(error),
      message: error instanceof RingPlaygroundError ? error.message : 'Probe stopped before completing all requested calls.',
    };
  }

  const reportPath = writeArtifacts(report, options.outputDirectory, now, process.cwd());
  const safeReport = redactProbeReport(report);
  output(JSON.stringify(safeReport, null, 2));
  output(`Redacted structure-only report saved to ${reportPath}.`);

  if (options.printDeviceIds) {
    output('Device IDs (local terminal only, do not paste):');
    if (devices.shapeUnrecognized) output('No IDs printed because the device-list response shape was unrecognized.');
    else if (devices.devices.length === 0) output('No device IDs were returned.');
    else for (const device of devices.devices) output(device.id);
  }

  if (!historyDeviceId) {
    output('Next: select a device in the Ring Developer Playground explorer or the app, set RING_HISTORY_DEVICE_ID in the ignored local .env, and rerun npm run ring:probe for Event History. This run called devices only; no History request was made.');
  }
  if (report.failure) process.exitCode = 1;
  return { reportPath, report: safeReport as Record<string, unknown> };
}
